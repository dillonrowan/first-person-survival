"""Tree and rock reactions to axe and pickaxe blows (run inside Blender).

Builds a "LocReactions" scene with one empty per clip, keyframes it, samples every frame at 30 fps
and writes src/world/LocReactionClips.ts. The empty is the loc's pivot: the middle of its footprint
on the ground. Axes: +X = the player's right, +Y = away from the player (the way the blow pushes),
+Z = up; offsets are in tiles (1 Blender unit = 1 tile). The open scene is left as it was; the
LocReactions scene stays in the file for a look.

Run from the repository root's Blender session, or set REPO before exec'ing this file.
"""
import math
import os

import bpy

REPO = globals().get("REPO") or os.getcwd()
OUT = os.path.join(REPO, "src", "world", "LocReactionClips.ts")
FPS = 30
D = math.radians

# Clip -> (length in frames, {channel: [(frame, value)]}); rot.* in degrees, loc.* in tiles.
CLIPS = {
    # A blow shudders the tree: the top whips away, swings back and settles.
    "treeHit": (18, {
        "rot.x": [(0, 0), (2, -4.5), (5, 2.2), (9, -1.3), (13, 0.5), (18, 0)],
        "rot.z": [(0, 0), (3, 1.2), (7, -0.8), (12, 0.3), (18, 0)],
    }),
    # The last log: the tree topples away from the player, bounces once and lies still.
    "treeFall": (42, {
        "rot.x": [(0, 0), (4, 2), (10, -8), (20, -38), (28, -86), (31, -80), (35, -88), (42, -88)],
        "rot.y": [(0, 0), (28, 6), (42, 6)],
        "loc.z": [(0, 0), (28, 0), (35, -0.12), (42, -0.15)],
    }),
    # A pick blow knocks the rock: a small jolt away and a squash.
    "rockHit": (9, {
        "loc.y": [(0, 0), (1, 0.04), (4, -0.01), (9, 0)],
        "loc.x": [(0, 0), (1, -0.02), (3, 0.015), (6, -0.005), (9, 0)],
        "scale.z": [(0, 1), (1, 0.95), (4, 1.01), (9, 1)],
        "scale.x": [(0, 1), (1, 1.025), (4, 0.995), (9, 1)],
        "scale.y": [(0, 1), (1, 1.025), (4, 0.995), (9, 1)],
    }),
    # The last ore: the rock shakes, then cracks down and shrinks (the empty rock shows after).
    "rockBreak": (15, {
        "loc.x": [(0, 0), (1, 0.03), (2, -0.03), (3, 0.025), (4, -0.02), (6, 0), (15, 0)],
        "loc.z": [(0, 0), (5, 0.02), (15, -0.3)],
        "scale.x": [(0, 1), (5, 1.04), (15, 0.55)],
        "scale.y": [(0, 1), (5, 1.04), (15, 0.55)],
        "scale.z": [(0, 1), (5, 0.97), (15, 0.35)],
    }),
}

PATHS = {"loc": "location", "rot": "rotation_euler", "scale": "scale"}
AXES = {"x": 0, "y": 1, "z": 2}


def build(scene):
    objects = {}
    for i, (name, (length, channels)) in enumerate(CLIPS.items()):
        obj = bpy.data.objects.get("pivot_" + name) or bpy.data.objects.new("pivot_" + name, None)
        if obj.name not in scene.collection.objects:
            scene.collection.objects.link(obj)
        obj.empty_display_type = "ARROWS"
        obj.animation_data_clear()
        obj.location = (i * 3, 0, 0)  # side by side for a look; the clips are relative to rest
        obj.rotation_euler = (0, 0, 0)
        obj.scale = (1, 1, 1)
        rest = tuple(obj.location)
        for channel, keys in channels.items():
            kind, axis = channel.split(".")
            path, index = PATHS[kind], AXES[axis]
            for frame, value in keys:
                v = D(value) if kind == "rot" else value + (rest[index] if kind == "loc" else 0)
                getattr(obj, path)[index] = v
                obj.keyframe_insert(data_path=path, index=index, frame=frame)
            getattr(obj, path)[index] = rest[index] if kind == "loc" else (1 if kind == "scale" else 0)
        obj.animation_data.action.name = name
        objects[name] = (obj, rest)
    return objects


def sample(scene, objects):
    out = {}
    for name, (obj, rest) in objects.items():
        length = CLIPS[name][0]
        frames = []
        for f in range(length + 1):
            scene.frame_set(f)
            loc = obj.matrix_basis.to_translation()
            q = obj.matrix_basis.to_quaternion()
            s = obj.matrix_basis.to_scale()
            frames.append([round(loc.x - rest[0], 4), round(loc.y - rest[1], 4), round(loc.z - rest[2], 4),
                           round(q.x, 5), round(q.y, 5), round(q.z, 5), round(q.w, 5),
                           round(s.x, 4), round(s.y, 4), round(s.z, 4)])
        out[name] = frames
    return out


def write(clips):
    lines = [
        "// Generated by tools/blender/loc_reactions.py (run in Blender); do not edit.",
        "//",
        "// Per frame at LOC_REACTION_FPS: offset x, y, z (tiles), rotation quaternion x, y, z, w and",
        "// scale x, y, z of the loc about its pivot (footprint middle, on the ground), in reaction axes:",
        "// +x the player's right, +y away from the player, +z up.",
        "",
        f"export const LOC_REACTION_FPS = {FPS};",
        "",
        "export const LOC_REACTION_CLIPS = {",
    ]
    for name, frames in clips.items():
        lines.append(f"    {name}: [")
        for fr in frames:
            lines.append("        [" + ", ".join(repr(v) for v in fr) + "],")
        lines.append("    ],")
    lines += ["} as const satisfies Record<string, readonly (readonly number[])[]>;", "",
              "export type LocReaction = keyof typeof LOC_REACTION_CLIPS;", ""]
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(lines))


window = bpy.context.window
previous = window.scene if window else bpy.context.scene
scene = bpy.data.scenes.get("LocReactions") or bpy.data.scenes.new("LocReactions")
scene.render.fps = FPS
if window:
    window.scene = scene
try:
    objects = build(scene)
    scene.frame_end = max(length for length, _ in CLIPS.values())
    write(sample(scene, objects))
finally:
    scene.frame_set(0)
    if window:
        window.scene = previous

result = {"written": OUT, "clips": {k: v[0] + 1 for k, v in CLIPS.items()}}
