"""Pickpocketing view motion (run inside Blender): the player's head while picking a pocket.

No hand is drawn: the first-person view itself shows the theft. Builds a "Pickpocket" scene with one
empty per clip (the player's eyes, looking along +Y) and writes
  src/skills/PickpocketClips.ts     per-frame head motion, sampled at 30 fps

Empty axes: +X the player's right, +Y ahead, +Z up; 1 Blender unit = 1 tile. Its location is the
eyes' offset (y: leaning in, z: ducking down), its rotation the look (x: pitch, up positive;
z: yaw, left positive; y: roll about the line of sight). Clips:
  reach   glance down at the mark's pocket and lean in, rummaging (2 game ticks)
  pocket  success: a quick innocent look away, back upright
  caught  failure: jerked upright and back, the view rattled
The open scene is left as it was. Set REPO before exec'ing this file, or run from the repository root.
"""
import math
import os

import bpy

REPO = globals().get("REPO") or os.getcwd()
CLIPS_OUT = os.path.join(REPO, "src", "skills", "PickpocketClips.ts")
FPS = 30
D = math.radians

REST = {"loc": (0, 0, 0), "rot": (0, 0, 0)}
DOWN = {"loc": (0, 0.08, -0.12), "rot": (-30, 3, 4)}

# Clip -> (length in frames, [(frame, pose or overrides)]); each key fills in from the previous one.
# rot in degrees (x pitch, y roll, z yaw), loc in tiles.
CLIPS = {
    # 36 frames = 2 game ticks, the time an attempt takes; it ends looking into the pocket.
    "reach": (36, [
        (0, REST),
        (6, {"loc": (0, 0.05, -0.07), "rot": (-22, 2, 7)}),
        (12, DOWN),
        (17, {"loc": (0, 0.09, -0.13), "rot": (-33, 1.5, 2.5)}),
        (22, {"loc": (0, 0.085, -0.12), "rot": (-29, 3.5, 5)}),
        (27, {"loc": (0, 0.095, -0.135), "rot": (-32, 2, 3)}),
        (32, {"loc": (0, 0.085, -0.12), "rot": (-30, 3, 4.5)}),
        (36, DOWN),
    ]),
    # Got it: a quick look away as if nothing happened, then upright.
    "pocket": (24, [
        (0, DOWN),
        (5, {"loc": (0, 0.03, -0.04), "rot": (-8, -1, -10)}),
        (12, {"loc": (0, 0, 0), "rot": (2, -1.5, -14)}),
        (24, REST),
    ]),
    # Caught: snapped upright and back, a rattle, then still (the stun holds the player).
    "caught": (24, [
        (0, DOWN),
        (2, {"loc": (0, -0.08, 0.02), "rot": (9, -7, -6)}),
        (4, {"loc": (0, -0.1, 0.01), "rot": (5, 5, 3)}),
        (6, {"loc": (0, -0.09, 0.015), "rot": (8, -4, -3)}),
        (9, {"loc": (0, -0.08, 0.01), "rot": (4, 2, 1)}),
        (14, {"loc": (0, -0.05, 0.0), "rot": (3, -0.5, 0)}),
        (24, REST),
    ]),
}


def fresh(name, scene):
    old = bpy.data.objects.get(name)
    if old:
        bpy.data.objects.remove(old, do_unlink=True)
    obj = bpy.data.objects.new(name, None)
    scene.collection.objects.link(obj)
    return obj


def build_clips(scene):
    objects = {}
    for i, (name, (length, keys)) in enumerate(CLIPS.items()):
        obj = fresh("head_" + name, scene)
        obj.empty_display_type = "CONE"
        obj.rotation_mode = "XYZ"
        pose = {}
        for frame, change in keys:
            pose = {**pose, **change}
            obj.location = pose["loc"]
            obj.rotation_euler = [D(a) for a in pose["rot"]]
            obj.keyframe_insert(data_path="location", frame=frame)
            obj.keyframe_insert(data_path="rotation_euler", frame=frame)
        obj.animation_data.action.name = name
        obj.delta_location = (i * 0.6, 0, 0)  # side by side for a look; sampling reads `location` only
        objects[name] = obj
    return objects


def sample(scene, objects):
    """Per frame: lean, dip (tiles), pitch, yaw, roll (radians) in the game's view terms."""
    out = {}
    for name, obj in objects.items():
        frames = []
        for f in range(CLIPS[name][0] + 1):
            scene.frame_set(f)
            loc, rot = obj.location, obj.rotation_euler
            # Roll: Blender's +Y roll tips the view's top right; the game's roll tips it left.
            frames.append([round(loc.y, 4), round(-loc.z, 4), round(rot.x, 5), round(rot.z, 5), round(-rot.y, 5)])
        out[name] = frames
    return out


def write_clips(clips):
    lines = [
        "// Generated by tools/blender/pickpocket.py (run in Blender); do not edit.",
        "//",
        "// Per frame at PICKPOCKET_CLIP_FPS: the first-person view while picking a pocket: lean ahead and",
        "// dip down (tiles), pitch (up positive), yaw (left positive) and roll (radians).",
        "",
        f"export const PICKPOCKET_CLIP_FPS = {FPS};",
        "",
        "export const PICKPOCKET_CLIPS = {",
    ]
    for name, frames in clips.items():
        lines.append(f"    {name}: [")
        lines += ["        [" + ", ".join(repr(v) for v in fr) + "]," for fr in frames]
        lines.append("    ],")
    lines += ["} as const satisfies Record<string, readonly (readonly number[])[]>;", "",
              "export type PickpocketClip = keyof typeof PICKPOCKET_CLIPS;", ""]
    with open(CLIPS_OUT, "w", newline="\n") as f:
        f.write("\n".join(lines))


window = bpy.context.window
previous = window.scene if window else bpy.context.scene
scene = bpy.data.scenes.get("Pickpocket") or bpy.data.scenes.new("Pickpocket")
scene.render.fps = FPS
if window:
    window.scene = scene
try:
    # The earlier hand model, its clip copies and the preview camera are no longer used.
    for o in list(scene.objects):
        if o.name.startswith(("pickpocket_hand", "fingers", "clip_", "pp_")):
            bpy.data.objects.remove(o, do_unlink=True)
    objects = build_clips(scene)
    scene.frame_start, scene.frame_end = 0, max(length for length, _ in CLIPS.values())
    write_clips(sample(scene, objects))
finally:
    scene.frame_set(0)
    if window:
        window.scene = previous

result = {"written": CLIPS_OUT, "clips": {k: v[0] + 1 for k, v in CLIPS.items()}}
