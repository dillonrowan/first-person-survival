def reset_pose():
    for pb in rig.pose.bones:
        pb.rotation_quaternion = (1, 0, 0, 0)
        pb.location = (0, 0, 0)


def apply_clip(name):
    clip = CLIPS[name]
    old = bpy.data.actions.get(name)
    if old:
        bpy.data.actions.remove(old)
    action = bpy.data.actions.new(name)
    action.use_fake_user = True
    rig.animation_data_create()
    rig.animation_data.action = action
    reset_pose()
    for track, keys in clip.items():
        if track == 'length':
            continue
        is_loc = track.endswith('.loc') or track.startswith('ik.')
        pb = rig.pose.bones[track[:-4] if track.endswith('.loc') else track]
        rest = pb.bone.matrix_local.to_quaternion()
        for f, v in keys:
            if is_loc:
                pb.location = rest.inverted() @ Vector(v)
                pb.keyframe_insert('location', frame=f)
            else:
                q = Euler([math.radians(a) for a in v], 'XYZ').to_quaternion()
                pb.rotation_quaternion = rest.inverted() @ q @ rest
                pb.keyframe_insert('rotation_quaternion', frame=f)
    bag = anim_utils.action_get_channelbag_for_slot(action, rig.animation_data.action_slot)
    if name != 'stun':
        for fc in bag.fcurves:
            # Snap into the impact; ease everywhere else.
            fc.keyframe_points[0].interpolation = 'LINEAR'
    return action


MADE = [apply_clip(n).name for n in CLIPS]
